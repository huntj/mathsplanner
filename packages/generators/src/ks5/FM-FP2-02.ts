// FM-FP2-02: Use group axioms, Cayley tables, subgroups, order, Lagrange's theorem and isomorphism
import * as A from "@mathsplanner/archetypes";
import { defineGenerator, reject, type QuestionDraft } from "@mathsplanner/core";
import { wrongs } from "../shared/angles.ts";
import { chosenText, numberAnswer } from "../shared/counting.ts";
import { gcdOf } from "../shared/fr.ts";

export interface Params {
  n: number;
  k: number;
  g: number;
  d: number;
  bad: number[];
}

export default defineGenerator<Params>({
  id: "FM-FP2-02",
  version: "1.0.0",
  depths: [1, 2, 4],
  misconceptions: ["ALG.GROUP"],

  params(rng) {
    const n = rng.pick([8, 9, 10, 12, 14, 15, 16, 18, 20]);
    const k = rng.int(2, n - 1);
    if (gcdOf(n, k) === 1 || n / gcdOf(n, k) === k)
      reject("an element whose order differs from itself and n");
    const g = rng.pick([12, 15, 18, 20, 21, 24, 28, 30]);
    const divisors = Array.from({ length: g - 2 }, (_, i) => i + 2).filter((x) => g % x === 0);
    const non = Array.from({ length: g - 2 }, (_, i) => i + 2).filter((x) => g % x !== 0 && x < g);
    const d = rng.pick(divisors);
    const bad = rng.shuffle(non).slice(0, 2);
    return { n, k, g, d, bad };
  },

  build(p, depth, rng): QuestionDraft {
    switch (depth) {
      case 1: {
        const order = p.n / gcdOf(p.n, p.k);
        return A.standard({
          question: [
            "In the group of integers modulo ",
            A.math(String(p.n)),
            " under addition, find the order of the element ",
            A.math(String(p.k)),
            ".",
          ],
          answer: A.number(order),
          wrong: wrongs(order, [
            {
              code: "ALG.GROUP",
              value: A.number(p.k),
              feedback: `The order is the smallest m with ${p.k}m ≡ 0 (mod ${p.n}), not the element itself.`,
            },
          ]),
          solution: [
            {
              say: `${p.k} × ${order} = ${p.k * order}, the first multiple of ${p.k} that is a multiple of ${p.n}.`,
            },
          ],
        });
      }
      case 2:
        return A.choice({
          rng,
          archetype: "varied-form",
          question: [`A group G has order ${p.g}.`],
          ask: "Which of these could be the order of a subgroup of G?",
          correct: String(p.d),
          distractors: p.bad.map((b) => ({
            content: String(b),
            code: "ALG.GROUP",
            feedback: `By Lagrange's theorem the order of a subgroup divides ${p.g}, and ${b} does not.`,
          })),
          solution: [
            { say: `Lagrange's theorem: subgroup orders divide ${p.g}. ${p.d} divides ${p.g}.` },
          ],
        });
      default:
        return A.trueOrFalseWhy({
          rng,
          statement: ["Ike says every group of order 4 is cyclic."],
          truth: false,
          reasons: [
            {
              text: "False. The Klein four-group {e, a, b, c}, where every element is its own inverse, has no element of order 4, so it is not cyclic.",
              correct: true,
            },
            {
              text: "True. 4 is small, so the group must be generated by one element.",
              code: "ALG.GROUP",
            },
            {
              text: "True. Every group of order n is isomorphic to the integers modulo n.",
              code: "ALG.GROUP",
            },
          ],
          solution: [
            {
              say: "For example, {1, 3, 5, 7} under multiplication modulo 8: every element squares to 1.",
            },
          ],
        });
    }
  },

  verify(p, question) {
    if (question.key.depth === 1) return numberAnswer(question) === p.n / gcdOf(p.n, p.k);
    if (question.key.depth === 2) return p.g % Number(chosenText(question)) === 0;
    return true;
  },
});
